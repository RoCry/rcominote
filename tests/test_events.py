"""Official Y8/Z8 field-table oracles and realistic interleaved BLE notifications.

Literal wire CRCs were produced independently with crcmod poly 0x18005,
initCrc=0, rev=True, xorOut=0. Payloads are hand-assigned source-table examples,
not captures or frames generated by the implementation under test.
"""

import asyncio
import unittest
from unittest.mock import AsyncMock, patch

from rcominote import protocol as P
from rcominote.connection import BUFFER_LIMIT, Connection

STATUS = bytes.fromhex("d22d010f14026401010509ff0102ff010b0c0d0e0f10111213ebba")
VOICE = bytes.fromhex("d22d0119070101020304aabb0b21")
SHORT_STATUS = bytes.fromhex("d22d010f13000000000000000000000000000000000000008a85")
SHORT_VOICE = bytes.fromhex("d22d01190401010203b570")
SERIAL = bytes.fromhex("d22d01010a4332363143463034333060bb")
ENTRY = bytes.fromhex("d22d010a1400323032363130313230383535343200001e7c01e12f")
LIST_END = bytes.fromhex("d22d010a01021fdb")
SIZE_THREE = bytes.fromhex("d22d010b0500000000035f6a")
DOWNLOAD_END = bytes.fromhex("d22d010b01024e1b")


class EventParsingTests(unittest.TestCase):
    def test_device_fields_match_official_y8_table_and_retain_unknown_tail(self):
        cmd, payload = P.parse(STATUS)
        self.assertEqual(
            P.parse_event(cmd, payload),
            {
                "event": "device_status",
                "charging": True,
                "battery": 100,
                "usb_mode": True,
                "mode": "call",
                "power_off_duration": 5,
                "noise_reduction": 9,
                "voice_control": None,
                "indicator_light": True,
                "segment_duration": 2,
                "screen_backlight": None,
                "usb_connected": True,
                "opcode": 15,
                "raw": "026401010509ff0102ff010b0c0d0e0f10111213",
            },
        )

    def test_voice_fields_match_z8_table_big_endian_and_retain_extension(self):
        cmd, payload = P.parse(VOICE)
        self.assertEqual(
            P.parse_event(cmd, payload),
            {
                "event": "voice_control",
                "enabled": True,
                "file_size": 16909060,
                "opcode": 25,
                "raw": "0101020304aabb",
            },
        )

    def test_source_boolean_false_and_memo_rules(self):
        result = P.parse_event(15, bytes.fromhex("0000020200000002000202000000000000000000"))
        self.assertEqual(
            [
                result[key]
                for key in (
                    "charging",
                    "usb_mode",
                    "mode",
                    "voice_control",
                    "indicator_light",
                    "screen_backlight",
                    "usb_connected",
                )
            ],
            [False, False, "memo", False, False, False, False],
        )

    def test_source_minimum_lengths_are_enforced(self):
        for packet, message in ((SHORT_STATUS, ">=20"), (SHORT_VOICE, ">=5")):
            with self.subTest(packet=packet.hex()), self.assertRaisesRegex(ValueError, message):
                P.parse_event(*P.parse(packet))


class EventRoutingTests(unittest.IsolatedAsyncioTestCase):
    async def asyncSetUp(self):
        client = AsyncMock()
        client.services.get_service = lambda _uuid: object()
        with patch("rcominote.connection.BleakClient", return_value=client):
            self.conn = Connection("replay")
        await self.conn.__aenter__()
        self.callbacks = {call.args[0]: call.args[1] for call in client.start_notify.await_args_list}

    async def asyncTearDown(self):
        await self.conn.__aexit__(None, None, None)

    def notify(self, packet, source=P.NOTIFY_CMD):
        self.callbacks[source](None, packet)

    async def test_idle_notifications_are_retained_once(self):
        self.notify(STATUS)
        self.notify(VOICE)
        events = await self.conn.watch(0.002)
        self.assertEqual(
            [(event["opcode"], event["frame"]) for event in events], [(15, STATUS.hex()), (25, VOICE.hex())]
        )
        self.assertEqual(await self.conn.watch(0.002), [])

    async def test_events_interleaved_with_command_are_not_lost(self):
        self.notify(STATUS)
        self.notify(SERIAL)
        self.notify(VOICE)
        self.assertEqual(await self.conn.serial(), "C261CF0430")
        self.assertEqual([event["opcode"] for event in await self.conn.watch(0.002)], [15, 25])

    async def test_events_between_file_entries_and_terminator(self):
        self.notify(ENTRY)
        self.notify(VOICE)
        self.notify(LIST_END)
        self.assertEqual([entry.name for entry in await self.conn.file_list()], ["20261012085542"])
        self.assertEqual([event["opcode"] for event in await self.conn.watch(0.002)], [25])

    async def test_events_between_download_chunks_preserve_output(self):
        self.notify(SIZE_THREE)
        self.notify(b"a", P.NOTIFY_OFFLINE)
        self.notify(STATUS)
        self.notify(b"bc", P.NOTIFY_OFFLINE)
        self.notify(VOICE)
        self.notify(DOWNLOAD_END)
        chunks = []
        self.assertEqual(await self.conn.download("recording", chunks.append), 3)
        self.assertEqual(b"".join(chunks), b"abc")
        self.assertEqual([event["opcode"] for event in await self.conn.watch(0.002)], [15, 25])

    async def wait_for_write(self):
        written = asyncio.Event()
        self.conn.client.write_gatt_char.side_effect = lambda *args, **kwargs: written.set()
        command = asyncio.create_task(self.conn.serial())
        watcher = asyncio.create_task(self.conn.watch(1))
        await written.wait()
        return command, watcher

    async def test_malformed_event_wakes_both_active_transaction_and_watch(self):
        command, watcher = await self.wait_for_write()
        self.notify(SHORT_STATUS)
        results = await asyncio.gather(command, watcher, return_exceptions=True)
        self.assertTrue(all(isinstance(result, ValueError) and ">=20" in str(result) for result in results))

    async def test_crc_error_when_idle_propagates_to_next_consumer(self):
        self.notify(VOICE[:-1] + b"\x00")
        with self.assertRaisesRegex(ValueError, "CRC mismatch"):
            await self.conn.watch(0.002)

    async def test_crc_error_wakes_both_active_transaction_and_watch(self):
        command, watcher = await self.wait_for_write()
        self.notify(VOICE[:-1] + b"\x00")
        results = await asyncio.gather(command, watcher, return_exceptions=True)
        self.assertTrue(
            all(isinstance(result, ValueError) and "CRC mismatch" in str(result) for result in results)
        )

    async def test_disconnect_wakes_both_active_transaction_and_watch(self):
        command, watcher = await self.wait_for_write()
        self.conn._dropped(None)
        results = await asyncio.gather(command, watcher, return_exceptions=True)
        self.assertTrue(all(isinstance(result, ConnectionError) for result in results))

    async def overflow_wakes_both(self, packet):
        command, watcher = await self.wait_for_write()
        for _ in range(BUFFER_LIMIT + 1):
            self.notify(packet)
        results = await asyncio.gather(command, watcher, return_exceptions=True)
        self.assertTrue(
            all(
                isinstance(result, RuntimeError) and "notification buffer exceeded" in str(result)
                for result in results
            )
        )

    async def test_event_buffer_overflow_wakes_both_consumers(self):
        await self.overflow_wakes_both(VOICE)

    async def test_transaction_buffer_overflow_wakes_both_consumers(self):
        await self.overflow_wakes_both(SERIAL)

    async def test_watch_total_output_is_bounded_even_if_queue_is_drained(self):
        for _ in range(3):
            self.notify(VOICE)
        with (
            patch("rcominote.connection.BUFFER_LIMIT", 2),
            self.assertRaisesRegex(RuntimeError, "watch exceeded 2 events"),
        ):
            await self.conn.watch(0.01)

    async def test_status_events_do_not_extend_command_or_download_deadline(self):
        async def noise():
            while True:
                self.notify(STATUS)
                await asyncio.sleep(0.001)

        for operation in (
            self.conn.command(1, timeout=0.01),
            self.conn.download("recording", lambda _data: None, timeout=0.01),
        ):
            self.notify(SIZE_THREE)
            producer = asyncio.create_task(noise())
            try:
                with self.assertRaisesRegex(TimeoutError, "deadline exceeded"):
                    await asyncio.wait_for(operation, timeout=0.1)
            finally:
                producer.cancel()
                await asyncio.gather(producer, return_exceptions=True)

    async def test_watch_duration_is_absolute_even_with_continuous_events(self):
        async def noise():
            while True:
                self.notify(VOICE)
                await asyncio.sleep(0.001)

        producer = asyncio.create_task(noise())
        try:
            events = await asyncio.wait_for(self.conn.watch(0.01), timeout=0.1)
            self.assertGreater(len(events), 0)
        finally:
            producer.cancel()
            await asyncio.gather(producer, return_exceptions=True)
